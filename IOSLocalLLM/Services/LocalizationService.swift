// MARK: - LocalizationService
//
// Live-switchable bilingual layer. iOS's built-in Bundle localization
// only updates at app launch (when AppleLanguages is read), so for a
// truly live "tap to switch" UX we keep translations in-process and
// expose a published `language` that views can observe.
//
// Strings are keyed by their English text so views can write either:
//
//     Text(loc.t("Settings"))
//     Text("Settings".tr)        // sugar
//
// and translations come from a single dictionary below. Missing keys
// fall back to the English key string (so a partial translation never
// renders empty UI).
//
// Adding a new language: extend `AppLanguage`, add another column in
// `translations`, and the settings picker picks it up automatically.

enum AppLanguage: String, CaseIterable, Identifiable {
    /// Follow the device's preferred language. If the system language
    /// matches a supported translation we use it; otherwise fall back to
    /// English.
    case system
    case english  = "en"
    case german   = "de"
    case french   = "fr"
    case spanish  = "es"
    case portuguese = "pt"
    case italian  = "it"
    case greek    = "el"
    case romanian = "ro"
    case russian  = "ru"
    case turkish  = "tr"
    case arabic   = "ar"
    case hindi    = "hi"
    case chinese  = "zh-Hans"
    case japanese = "ja"
    case korean   = "ko"

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .system:     return "System default"
        case .english:    return "English"
        case .german:     return "Deutsch"
        case .french:     return "Français"
        case .spanish:    return "Español"
        case .portuguese: return "Português"
        case .italian:    return "Italiano"
        case .greek:      return "Ελληνικά"
        case .romanian:   return "Română"
        case .russian:    return "Русский"
        case .turkish:    return "Türkçe"
        case .arabic:     return "العربية"
        case .hindi:      return "हिन्दी"
        case .chinese:    return "简体中文"
        case .japanese:   return "日本語"
        case .korean:     return "한국어"
        }
    }

    /// Native-name display used in the picker so each language reads
    /// recognisably regardless of the currently active translation.
    var nativeName: String {
        switch self {
        case .system:     return "Auto"
        case .english:    return "English"
        case .german:     return "Deutsch"
        case .french:     return "Français"
        case .spanish:    return "Español"
        case .portuguese: return "Português"
        case .italian:    return "Italiano"
        case .greek:      return "Ελληνικά"
        case .romanian:   return "Română"
        case .russian:    return "Русский"
        case .turkish:    return "Türkçe"
        case .arabic:     return "العربية"
        case .hindi:      return "हिन्दी"
        case .chinese:    return "简体中文"
        case .japanese:   return "日本語"
        case .korean:     return "한국어"
        }
    }
}

// NB: Deliberately NOT @MainActor on the class. Property initialisers
// like `@ObservedObject private var loc = LocalizationService.shared`
// run in whatever context the surrounding View struct is being
// instantiated in — SwiftUI does some of its diffing work on background
// threads, and isolating `shared` to MainActor crashed on launch with a
// "Crash: data race" once `uiLanguage = "tr"` was persisted (the very
// first view created off-main hit the MainActor barrier). The published
// property mutation does need to be on main; we route through
// MainActor.assumeIsolated in setLanguage for that. Read paths (`t`)
// are pure value lookups over an immutable dictionary and are safe
// from any thread.
final class LocalizationService: ObservableObject, @unchecked Sendable {

    static let shared = LocalizationService()

    /// Drives all reactive view re-renders when the user picks a new
    /// language. Backed by AppSettings.uiLanguage so the choice persists
    /// across launches.
    @Published private(set) var language: AppLanguage

    private init() {
        let raw = UserDefaults.standard.string(forKey: "uiLanguage") ?? AppLanguage.system.rawValue
        self.language = AppLanguage(rawValue: raw) ?? .system
    }

    /// Programmatically change the active language. Persists to
    /// UserDefaults and publishes the change so observing views update
    /// in place — no app restart required. The published mutation is
    /// hopped onto the main actor so SwiftUI's observation pipeline
    /// receives the change on the thread it expects.
    func setLanguage(_ new: AppLanguage) {
        guard new != language else { return }
        UserDefaults.standard.set(new.rawValue, forKey: "uiLanguage")
        if Thread.isMainThread {
            language = new
        } else {
            DispatchQueue.main.async { [weak self] in
                self?.language = new
            }
        }
    }

    /// Resolves an English source string to the user's chosen language.
    /// Falls back to the English source if no translation is registered,
    /// so the UI never goes blank for a missing key. Safe to call from
    /// any thread — reads an immutable lookup table.
    func t(_ key: String) -> String {
        let effective: AppLanguage = {
            if language != .system { return language }
            let preferred = Locale.preferredLanguages.first ?? "en"
            if preferred.hasPrefix("de") { return .german }
            if preferred.hasPrefix("fr") { return .french }
            if preferred.hasPrefix("es") { return .spanish }
            if preferred.hasPrefix("pt") { return .portuguese }
            if preferred.hasPrefix("it") { return .italian }
            if preferred.hasPrefix("el") { return .greek }
            if preferred.hasPrefix("ro") { return .romanian }
            if preferred.hasPrefix("ru") { return .russian }
            if preferred.hasPrefix("tr") { return .turkish }
            if preferred.hasPrefix("ar") { return .arabic }
            if preferred.hasPrefix("hi") { return .hindi }
            if preferred.hasPrefix("zh") { return .chinese }
            if preferred.hasPrefix("ja") { return .japanese }
            if preferred.hasPrefix("ko") { return .korean }
            return .english
        }()
        switch effective {
        case .english, .system: return key
        case .german:           return Self.de[key] ?? key
        case .french:           return Self.fr[key] ?? key
        case .spanish:          return Self.es[key] ?? key
        case .portuguese:       return Self.pt[key] ?? key
        case .italian:          return Self.it[key] ?? key
        case .greek:            return Self.el[key] ?? key
        case .romanian:         return Self.ro[key] ?? key
        case .russian:          return Self.ru[key] ?? key
        case .turkish:          return Self.tr[key] ?? key
        case .arabic:           return Self.ar[key] ?? key
        case .hindi:            return Self.hi[key] ?? key
        case .chinese:          return Self.zh[key] ?? key
        case .japanese:         return Self.ja[key] ?? key
        case .korean:           return Self.ko[key] ?? key
        }
    }

    // MARK: - Turkish translations
    //
    // Keyed by the English source string used in `Text(...)` /
    // `Button(...)` / etc. New translations get appended here — order
    // doesn't matter but it helps to group related strings together.
    //
    // NB: built from an `[(String, String)]` tuple list using
    // `Dictionary(_:uniquingKeysWith:)` instead of a dictionary literal.
    // Dictionary literals trap with "Fatal error: Dictionary literal
    // contains duplicate keys" if any key appears twice — which crashed
    // the app on launch the moment a user selected Turkish. The
    // uniquingKeysWith form silently keeps the first value on a
    // duplicate, so a translation typo can't ever crash the process.

    private static let tr: [String: String] = Dictionary(trEntries, uniquingKeysWith: { first, _ in first })

